import {
  parsePnpmProject,
  parseYarnLockV1Project,
  parseYarnLockV2Project,
} from '../../../lib';
import type { PruneLevel } from '../../../lib/dep-graph-builders/types';

// A package reachable from both a prod and a dev dependency is prod, as npm and pnpm label it.
// Here kind-of is a direct prod dependency and is also required by is-number, a direct
// devDependency. The simple yarn builders revisited kind-of under is-number and the last (dev)
// visit overwrote its labels, so kind-of and its transitive is-buffer came out as dev.
const pkgJson = JSON.stringify({
  name: 'shared-prod-dev',
  version: '1.0.0',
  dependencies: { 'kind-of': '^3.0.2' },
  devDependencies: { 'is-number': '^3.0.0' },
});

const yarnLockV1 = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


is-buffer@^1.1.5:
  version "1.1.6"
  resolved "https://registry.yarnpkg.com/is-buffer/-/is-buffer-1.1.6.tgz"

is-number@^3.0.0:
  version "3.0.0"
  resolved "https://registry.yarnpkg.com/is-number/-/is-number-3.0.0.tgz"
  dependencies:
    kind-of "^3.0.2"

kind-of@^3.0.2:
  version "3.2.2"
  resolved "https://registry.yarnpkg.com/kind-of/-/kind-of-3.2.2.tgz"
  dependencies:
    is-buffer "^1.1.5"
`;

const yarnLockV2 = `__metadata:
  version: 6
  cacheKey: 8

"is-buffer@npm:^1.1.5":
  version: 1.1.6
  resolution: "is-buffer@npm:1.1.6"
  languageName: node
  linkType: hard

"is-number@npm:^3.0.0":
  version: 3.0.0
  resolution: "is-number@npm:3.0.0"
  dependencies:
    kind-of: ^3.0.2
  languageName: node
  linkType: hard

"kind-of@npm:^3.0.2":
  version: 3.2.2
  resolution: "kind-of@npm:3.2.2"
  dependencies:
    is-buffer: ^1.1.5
  languageName: node
  linkType: hard

"shared-prod-dev@workspace:.":
  version: 0.0.0-use.local
  resolution: "shared-prod-dev@workspace:."
  dependencies:
    is-number: ^3.0.0
    kind-of: ^3.0.2
  languageName: unknown
  linkType: soft
`;

const expected = {
  'kind-of@3.2.2': 'prod',
  'is-buffer@1.1.6': 'prod',
  'is-number@3.0.0': 'dev',
};

const scopes = (
  dg: Awaited<ReturnType<typeof parseYarnLockV2Project>>,
  label: string,
) =>
  Object.fromEntries(
    dg
      .toJSON()
      .graph.nodes.filter((n) => n.nodeId !== 'root-node')
      .map((n) => [n.pkgId, n.info?.labels?.[label]]),
  );

describe('yarn: a package shared by prod and dev dependencies is labelled prod', () => {
  it.each<PruneLevel>(['none', 'withinTopLevelDeps', 'cycles'])(
    'yarn v1 (pruneLevel: %s)',
    async (pruneLevel) => {
      const dg = await parseYarnLockV1Project(pkgJson, yarnLockV1, {
        includeDevDeps: true,
        includeOptionalDeps: true,
        includePeerDeps: false,
        strictOutOfSync: false,
        pruneLevel,
        showNpmScope: true,
      });
      expect(scopes(dg, 'scope')).toEqual(expected);
      expect(scopes(dg, 'npm:scope')).toEqual(expected);
    },
  );

  it.each([false, true])(
    'yarn berry (pruneWithinTopLevelDeps: %s)',
    async (pruneWithinTopLevelDeps) => {
      const dg = await parseYarnLockV2Project(pkgJson, yarnLockV2, {
        includeDevDeps: true,
        includeOptionalDeps: true,
        strictOutOfSync: false,
        pruneWithinTopLevelDeps,
        showNpmScope: true,
      });
      expect(scopes(dg, 'scope')).toEqual(expected);
      expect(scopes(dg, 'npm:scope')).toEqual(expected);
    },
  );
});

const pnpmLock = `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      kind-of:
        specifier: ^3.0.2
        version: 3.2.2
    devDependencies:
      is-number:
        specifier: ^3.0.0
        version: 3.0.0

packages:

  is-buffer@1.1.6:
    resolution: {integrity: sha512-isbuffer}

  is-number@3.0.0:
    resolution: {integrity: sha512-isnumber}

  kind-of@3.2.2:
    resolution: {integrity: sha512-kindof}

snapshots:

  is-buffer@1.1.6: {}

  is-number@3.0.0:
    dependencies:
      kind-of: 3.2.2

  kind-of@3.2.2:
    dependencies:
      is-buffer: 1.1.6
`;

describe('pnpm: a package shared by prod and dev dependencies is labelled prod', () => {
  it.each([false, true])(
    'pnpm (pruneWithinTopLevelDeps: %s)',
    async (pruneWithinTopLevelDeps) => {
      const dg = await parsePnpmProject(pkgJson, pnpmLock, {
        includeDevDeps: true,
        includeOptionalDeps: true,
        strictOutOfSync: false,
        pruneWithinTopLevelDeps,
        showNpmScope: true,
      });
      expect(scopes(dg, 'scope')).toEqual(expected);
      expect(scopes(dg, 'npm:scope')).toEqual(expected);
    },
  );
});

// A name listed in both dependencies and devDependencies. getTopLevelDeps lets the
// devDependencies entry win, and a production scan (includeDevDeps: false) leaves the package
// out. With --dev it is labelled dev in every builder, the same as npm and pnpm, so the
// production and --dev scans agree. Before OSM-3760 the simple yarn builders labelled the
// direct node prod and its subtree dev.
describe('a name in both dependencies and devDependencies', () => {
  const overlapPkgJson = JSON.stringify({
    name: 'overlap',
    version: '1.0.0',
    dependencies: { 'kind-of': '^3.0.2' },
    devDependencies: { 'kind-of': '^3.0.2' },
  });
  const overlapV1 = `# yarn lockfile v1


is-buffer@^1.1.5:
  version "1.1.6"
  resolved "https://registry.yarnpkg.com/is-buffer/-/is-buffer-1.1.6.tgz"

kind-of@^3.0.2:
  version "3.2.2"
  resolved "https://registry.yarnpkg.com/kind-of/-/kind-of-3.2.2.tgz"
  dependencies:
    is-buffer "^1.1.5"
`;
  const overlapV2 = `__metadata:
  version: 6
  cacheKey: 8

"is-buffer@npm:^1.1.5":
  version: 1.1.6
  resolution: "is-buffer@npm:1.1.6"
  languageName: node
  linkType: hard

"kind-of@npm:^3.0.2":
  version: 3.2.2
  resolution: "kind-of@npm:3.2.2"
  dependencies:
    is-buffer: ^1.1.5
  languageName: node
  linkType: hard

"overlap@workspace:.":
  version: 0.0.0-use.local
  resolution: "overlap@workspace:."
  dependencies:
    kind-of: ^3.0.2
  languageName: unknown
  linkType: soft
`;
  const allDev = { 'kind-of@3.2.2': 'dev', 'is-buffer@1.1.6': 'dev' };

  it.each<PruneLevel>(['none', 'withinTopLevelDeps', 'cycles'])(
    'yarn v1 (pruneLevel: %s)',
    async (pruneLevel) => {
      for (const includeDevDeps of [true, false]) {
        const dg = await parseYarnLockV1Project(overlapPkgJson, overlapV1, {
          includeDevDeps,
          includeOptionalDeps: true,
          includePeerDeps: false,
          strictOutOfSync: false,
          pruneLevel,
          showNpmScope: true,
        });
        expect(scopes(dg, 'scope')).toEqual(includeDevDeps ? allDev : {});
      }
    },
  );

  it.each([false, true])(
    'yarn berry (pruneWithinTopLevelDeps: %s)',
    async (pruneWithinTopLevelDeps) => {
      for (const includeDevDeps of [true, false]) {
        const dg = await parseYarnLockV2Project(overlapPkgJson, overlapV2, {
          includeDevDeps,
          includeOptionalDeps: true,
          strictOutOfSync: false,
          pruneWithinTopLevelDeps,
          showNpmScope: true,
        });
        expect(scopes(dg, 'scope')).toEqual(includeDevDeps ? allDev : {});
      }
    },
  );
});

// A workspace member's dev-only entry can be visited before one of its prod entries. Here
// @demo/lib depends on ms and has debug as a devDependency, and debug also requires ms. The
// lockfile lists debug first, so ms was first reached through debug and labelled dev. The later
// prod path must relabel ms (and its subtree) as prod.
describe('yarn berry workspace: prod entry reached first through a dev-only entry', () => {
  const appPkgJson = JSON.stringify({
    name: '@demo/app',
    version: '1.0.0',
    dependencies: { '@demo/lib': 'workspace:*' },
  });
  const workspacePackages = {
    '@demo/app': { dependencies: { '@demo/lib': 'workspace:*' } },
    '@demo/lib': {
      dependencies: { ms: '^2.1.0' },
      devDependencies: { debug: '^4.3.0' },
    },
  };
  const lock = `__metadata:
  version: 6
  cacheKey: 8

"@demo/app@workspace:apps/app":
  version: 0.0.0-use.local
  resolution: "@demo/app@workspace:apps/app"
  dependencies:
    "@demo/lib": "workspace:*"
  languageName: unknown
  linkType: soft

"@demo/lib@workspace:*, @demo/lib@workspace:libs/lib":
  version: 0.0.0-use.local
  resolution: "@demo/lib@workspace:libs/lib"
  dependencies:
    debug: ^4.3.0
    ms: ^2.1.0
  languageName: unknown
  linkType: soft

"debug@npm:^4.3.0":
  version: 4.3.4
  resolution: "debug@npm:4.3.4"
  dependencies:
    ms: 2.1.2
  languageName: node
  linkType: hard

"ms@npm:2.1.2, ms@npm:^2.1.0":
  version: 2.1.2
  resolution: "ms@npm:2.1.2"
  languageName: node
  linkType: hard
`;

  it.each([false, true])(
    'labels ms prod and debug dev (pruneWithinTopLevelDeps: %s)',
    async (pruneWithinTopLevelDeps) => {
      const dg = await parseYarnLockV2Project(
        appPkgJson,
        lock,
        {
          includeDevDeps: true,
          includeOptionalDeps: true,
          strictOutOfSync: false,
          pruneWithinTopLevelDeps,
          showNpmScope: true,
        },
        {
          isRoot: false,
          isWorkspacePkg: true,
          rootResolutions: {},
          workspacePackages,
        },
      );
      const s = scopes(dg, 'scope');
      expect(s['@demo/lib@0.0.0-use.local']).toBe('prod');
      expect(s['debug@4.3.4']).toBe('dev');
      expect(s['ms@2.1.2']).toBe('prod');
    },
  );
});
